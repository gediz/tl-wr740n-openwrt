#!/bin/bash
# SPDX-License-Identifier: MIT
# Build the routernet test image: the malta web image (same userspace, overlay and test hooks as build-web.sh)
# with the TL-WR740N kernel's networking trim. This is the pre-flash QEMU check (README.md).
#
# Kernel: plain malta be config-default plus the "# Networking" block of ../build/kernel-trim.config and the
# networking options of its "# Round 2" (ETHTOOL_NETLINK, SYN_COOKIES), read from that file on every run so the
# two stay in step. Effective values are compared with the router's built kernel .config (routernet-kconfig.txt).
# Output: images-routernet/ (vmlinux.elf, rootfs ext4, variant B, squashfs, overlay disk, config-default,
# kernel.config, routernet-kconfig.txt). About 3 to 5 min.
# Afterwards the tree goes back to the plain setup (config-default, files, .config) and the kernel is cleaned,
# so the next plain build rebuilds the stock malta kernel.
set -e
Q=$(cd "$(dirname "$0")" && pwd)
C=${CONTAINER:-owrt-src-malta}; J=${JOBS:-$(nproc)}
T=$Q/../build/kernel-trim.config
RK=$Q/../build/src/build_dir/target-mips_24kc_musl/linux-ath79_tiny/linux-6.6.144/.config
O=$Q/images-routernet
PLAIN=$Q/config-default.malta-be.plain
CD=$Q/src/target/linux/malta/be/config-default
docker start $C >/dev/null
cmp -s $CD $PLAIN || { echo "config-default is not the plain one ($PLAIN), stop"; exit 1; }
mkdir -p $O
restore() {  # back to the plain setup (build-web.sh end state); runs on any exit
  cp $PLAIN $CD
  docker exec $C bash -c 'cd /src && make target/linux/clean package/kernel/linux/clean package/kernel/mac80211/clean package/feeds/packages/mdio-netlink/clean package/busybox/clean' >/dev/null 2>&1
  NO_WEB=1 $Q/../build/prepare-files.sh $Q/src/files >/dev/null
  cp $Q/diffconfig-malta.txt $Q/src/.config
  md5sum $CD $Q/src/.config
}
trap restore EXIT
{ cat $PLAIN
  echo "# routernet: networking options of ../build/kernel-trim.config (router kernel trim), generated by build-routernet.sh"
  sed -n '/^# Networking/,/^# Ethernet/p' $T | grep '^# CONFIG_\|^CONFIG_'
  sed -n '/^# Round 2/,/^# Round 3/p' $T | grep -E 'CONFIG_(ETHTOOL_NETLINK|SYN_COOKIES)[ =]'
} > $O/config-default
cp $O/config-default $CD
$Q/../build/prepare-files.sh $Q/src/files
cp -a $Q/files-malta-test/. $Q/src/files/
chmod -R go-w $Q/src/files
sed 's#^CONFIG_BINARY_FOLDER=.*#CONFIG_BINARY_FOLDER="/src/bin-routernet"#' $Q/diffconfig-malta-web.txt > $O/diffconfig
cp $O/diffconfig $Q/src/.config
T0=$(date +%s)
docker exec $C bash -c 'cd /src && make defconfig >/dev/null && make target/linux/clean package/kernel/linux/clean package/kernel/mac80211/clean package/feeds/packages/mdio-netlink/clean package/busybox/clean && make -j'$J > $O/build.log 2>&1 || rc=$?
echo "build rc=${rc:-0} in $(( $(date +%s) - T0 )) s" | tee -a $O/build.log
[ -z "$rc" ] || exit $rc
K=$Q/src/build_dir/target-mips_24kc_musl/linux-malta_be/linux-6.6.144
cp $K/.config $O/kernel.config
# every option the trim names: value in the router's built kernel and in this malta kernel
v() { grep -E "^$o=|^# $o is not set" $1 | sed "s/^# $o is not set/n/; s/^$o=//" | head -n 1; }
{ echo "option router malta"
  for o in $(sed -n '/^# routernet/,$p' $O/config-default | grep -oE 'CONFIG_[A-Z0-9_]+' | sort -u) CONFIG_BRIDGE_VLAN_FILTERING CONFIG_VLAN_8021Q CONFIG_BRIDGE; do
    echo "$o $(v $RK) $(v $O/kernel.config)"
  done; } > $O/routernet-kconfig.txt
B=$Q/src/bin-routernet/targets/malta/be
cp $B/openwrt-malta-be-vmlinux.elf $O/vmlinux.elf
cp $B/openwrt-malta-be-rootfs-ext4.img.gz $B/openwrt-malta-be-default.manifest $B/openwrt-malta-be-rootfs-squashfs.img.gz $O/
ln -sfn openwrt-malta-be-rootfs-ext4.img.gz $O/rootfs-ext4.img
# variant B and the overlay disk, as in build-web.sh
docker exec $C bash -c 'set -e; cd /tmp; zcat /out/images-routernet/openwrt-malta-be-rootfs-ext4.img.gz > b.ext4
  echo B > fw-variant; debugfs -w -R "write fw-variant /etc/fw-variant" b.ext4 >/dev/null
  debugfs -R "cat /etc/fw-variant" b.ext4; gzip -9n -c b.ext4 > /out/images-routernet/variant-b-rootfs-ext4.img.gz; rm -f b.ext4 fw-variant'
docker exec $C bash -c 'set -e; cd /tmp; zcat /out/images-routernet/openwrt-malta-be-rootfs-squashfs.img.gz > o.img
  off=$(( ($(od -An -t u8 -j 40 -N 8 o.img) + 65535) / 65536 * 65536 )); truncate -s $off o.img
  truncate -s 16M ov.ext4; mkfs.ext4 -q -F -L rootfs_data ov.ext4; cat ov.ext4 >> o.img
  echo "overlay at $off"; gzip -9n -c o.img > /out/images-routernet/overlay-disk.img.gz; rm -f o.img ov.ext4'
cat $O/routernet-kconfig.txt
ls -l $O
